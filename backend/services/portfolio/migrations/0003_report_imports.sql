-- Report upload flow in the app: the list of supported brokers comes from
-- here, and every uploaded report gets a row the app can poll while the
-- parser works on it.

-- Brokers whose reports the parser can read. id is the parser's broker
-- key (parser/cmd/main.go registers a parser per key) and is what the app
-- sends back as the "broker" form field on upload. A new broker = a parser
-- in the parser service + a row here.
CREATE TABLE IF NOT EXISTS brokers (
    id           TEXT PRIMARY KEY,
    name         TEXT NOT NULL,
    -- Accepted file extensions, lower case, without the dot.
    file_formats TEXT[] NOT NULL,
    -- Absolute URL or a path on gateway; NULL - the app draws a letter.
    icon_url     TEXT,
    color        TEXT, -- brand color "#RRGGBB"
    sort_order   INT NOT NULL DEFAULT 0,
    enabled      BOOLEAN NOT NULL DEFAULT TRUE
);

