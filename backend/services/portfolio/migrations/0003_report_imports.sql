-- One uploaded report on its way through the parser:
-- queued -> processing -> done | failed. id = task_id of the
-- report.uploaded message (generated by gateway).
CREATE TABLE IF NOT EXISTS report_imports (
    id                      UUID PRIMARY KEY,
    portfolio_id            UUID NOT NULL REFERENCES portfolios (id) ON DELETE CASCADE,
    broker_id               TEXT NOT NULL REFERENCES brokers (id),
    filename                TEXT NOT NULL DEFAULT '',
    status                  TEXT NOT NULL DEFAULT 'queued'
                                CHECK (status IN ('queued', 'processing', 'done', 'failed')),
    error                   TEXT NOT NULL DEFAULT '',
    trades_created          INT NOT NULL DEFAULT 0,
    trades_skipped          INT NOT NULL DEFAULT 0,
    cash_operations_created INT NOT NULL DEFAULT 0,
    cash_operations_skipped INT NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at             TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_report_imports_portfolio_id_created_at
    ON report_imports (portfolio_id, created_at DESC);
